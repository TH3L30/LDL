def _measure(art: str) -> Tuple[int, int]:
    """Return (max_line_width, height) of a banner."""
    lines = art.split("\n")
    return (max((len(l.rstrip()) for l in lines), default=0), len(lines))


_META: List[Tuple[int, int]] = [_measure(a) for a in BANNERS]


def fitting_indexes(max_width: int) -> List[int]:
    """Indexes of banners whose width fits in max_width columns."""
    return [i for i, (w, _h) in enumerate(_META) if w <= max_width]


def pick_banner(max_width: int) -> Optional[str]:
    """Random banner fitting max_width, or None when nothing fits."""
    idx = fitting_indexes(max_width)
    if not idx:
        return None
    return BANNERS[random.choice(idx)]


def get_banner(n: int) -> str:
    """1-based lookup for --banner N. Raises ValueError out of range."""
    if not 1 <= n <= len(BANNERS):
        raise ValueError(f"banner number must be 1-{len(BANNERS)}, got {n}")
    return BANNERS[n - 1]


