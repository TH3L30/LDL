SPLASH_DURATION = 4.0  # seconds for the dissolve-in effect (within 3-6s)
SPLASH_FPS = 25

_BLANK_CELLS = (" ", "⠀")  # space + braille blank: background, always visible


def grid_size(art: str) -> Tuple[int, int]:
    """Return (rows, cols) of the art grid."""
    lines = art.split("\n")
    rows = len(lines)
    cols = max((len(l.rstrip()) for l in lines), default=0)
    return rows, cols


# ---------------------------------------------------------------------------
# High-quality fit-to-box scaler (dot-level braille resample)
# ---------------------------------------------------------------------------
# A braille cell (U+2800-U+28FF) encodes a 2x4 dot matrix. Naive scaling
# (dropping lines/columns) mangles portraits; instead we decode to dots,
# area-average down to the target grid, threshold, and re-encode. This
# preserves recognizable shapes even at extreme ratios (e.g. 118x40 -> 24x8).

# bit i (dot i+1) -> (x, y) in the 2x4 cell
_DOT_POS = ((0, 0), (0, 1), (0, 2), (1, 0), (1, 1), (1, 2), (0, 3), (1, 3))


def _decode_char(ch: str):
    """Return set of (x, y) dots lit in a braille char. Non-braille chars
    (space, regular text) count as blank."""
    o = ord(ch) - 0x2800
    if o < 0 or o > 0xFF:
        return ()
    return tuple((x, y) for i, (x, y) in enumerate(_DOT_POS) if o & (1 << i))


def _encode_cell(dots) -> str:
    """Pack an iterable of (x, y) dots into one braille char."""
    code = 0
    for (x, y) in dots:
        for i, (dx, dy) in enumerate(_DOT_POS):
            if dx == x and dy == y:
                code |= (1 << i)
                break
    return chr(0x2800 + code)


def scale_art(art: str, cols: int, rows: int, threshold: float = 0.5):
    """Scale art to fit inside cols x rows chars, aspect preserved.

    Returns exactly `rows` Naive-strings (blank-padded, vertically
    centered); each line is at most `cols` chars. Never upscales
    (scale capped at 1.0) since minis are always smaller than sources.
    """
    if cols <= 0 or rows <= 0:
        return [""] * max(1, rows)
    src = [l.rstrip() for l in art.split("\n")]
    sw_chars = max((len(l) for l in src), default=0)
    sh_chars = len(src)
    if sw_chars == 0 or sh_chars == 0:
        return [""] * rows
    sw, sh = sw_chars * 2, sh_chars * 4
    # dot bitmap
    bmp = [[0.0] * sw for _ in range(sh)]
    for r, line in enumerate(src):
        for c, ch in enumerate(line):
            if ch == " " or ch == "⠀":
                continue
            base = ord(ch) - 0x2800
            if base < 0 or base > 0xFF:
                continue  # non-braille ink (e.g. "(o)") treated as blank
            for i, (dx, dy) in enumerate(_DOT_POS):
                if base & (1 << i):
                    bmp[r * 4 + dy][c * 2 + dx] = 1.0
    s = min(cols / sw_chars, rows / sh_chars)
    if s > 1.0:
        s = 1.0
    oc = max(1, int(round(sw_chars * s)))
    orr = max(1, int(round(sh_chars * s)))
    oc = min(oc, cols)
    orr = min(orr, rows)
    # sample each output dot from the source rect, threshold, repack
    out_dots_w, out_dots_h = oc * 2, orr * 4
    lit = [[False] * out_dots_w for _ in range(out_dots_h)]
    for oy in range(out_dots_h):
        y0 = int(oy / s)
        y1 = max(y0 + 1, int((oy + 1) / s))
        for ox in range(out_dots_w):
            x0 = int(ox / s)
            x1 = max(x0 + 1, int((ox + 1) / s))
            total = 0.0
            count = 0
            for sy in range(y0, min(y1, sh)):
                row = bmp[sy]
                for sx in range(x0, min(x1, sw)):
                    total += row[sx]
                    count += 1
            if count and total / count >= threshold:
                lit[oy][ox] = True
    out_lines = []
    for r in range(orr):
        line_chars = []
        for c in range(oc):
            dots = [(dx, dy) for dy in range(4) for dx in range(2)
                    if lit[r * 4 + dy][c * 2 + dx]]
            # plain space for empty cells so lines rstrip cleanly
            line_chars.append(_encode_cell(dots) if dots else " ")
        out_lines.append("".join(line_chars).rstrip(" "))
    # vertical centering to exactly `rows` lines
    top = max(0, (rows - len(out_lines)) // 2)
    padded = [""] * top + out_lines
    while len(padded) < rows:
        padded.append("")
    return padded[:rows]


def iter_cells(art: str):
    """Yield (row, col, char) for every ink cell.

    Background cells (spaces, braille blanks) are skipped: they stay
    visible from the first frame so the silhouette holds its layout
    while the ink dissolves in around them.
    """
    lines = [l.rstrip() for l in art.split("\n")]
    rows, cols = grid_size(art)
    for r in range(rows):
        line = lines[r] if r < len(lines) else ""
        for c in range(cols):
            ch = line[c] if c < len(line) else " "
            if ch not in _BLANK_CELLS:
                yield (r, c, ch)
